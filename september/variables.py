"""
RULES FOR WRITING VARIABLES IN PYTHON:

1. Variable names can contain letters, numbers, and underscores.
2. A variable name cannot start with a number.
3. Variable names cannot contain spaces.
4. Do not use special characters like @, #, $, %, etc.
5. Variable names are case-sensitive.
   age and Age are different variables.
6. Do not use Python keywords as variable names.
   Example: if, for, while, class, True, False
7. Use meaningful variable names whenever possible.
8. Prefer snake_case for multi-word variable names.
   Example: student_name, total_marks
"""
price = 10
rating = 4.9
name = 'sambhav'
is_published = True

print(price)
print(rating)
print(name)
print(is_published)


